var update = flag.Bool("update", false, "rewrite the formal models under formal/")

// refreshConstants is formal/RefreshConstants.tla: the lease a refresh
// claims and the longest the refresh holds it, in the whole seconds the
// TLA+ model counts in. The lease rounds down and the request up, so the
// model never gives a refresh more room than the code does.
func refreshConstants() string {
	return fmt.Sprintf(`\* Code generated by TestRefreshConstants in internal/signin. DO NOT EDIT.
--------------------------- MODULE RefreshConstants ---------------------------
Lease == %d
Budget == %d
=============================================================================
`, refreshLease/time.Second, (tokenTimeout+time.Second-1)/time.Second)
}

// TestRefreshConstants holds formal/RefreshConstants.tla to the Go
// constants, so the tla gate checks formal/Refresh.tla against the lease and
// the request time the refresh runs with. Rerun with -update after changing
// one.
func TestRefreshConstants(t *testing.T) {
	path := filepath.Join("..", "..", "formal", "RefreshConstants.tla")
	want := refreshConstants()
	if *update {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v; rerun with -update", path, err)
	}
	if string(got) != want {
		t.Fatalf("%s differs from the refresh constants; rerun go test ./internal/signin -run TestRefreshConstants -update\n--- want\n%s--- got\n%s", path, want, got)
	}
}
